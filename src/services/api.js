import axios from "axios";

const API = axios.create({
  baseURL: "http://127.0.0.1:8000/api",
  timeout: 120000, // 2 minutes for large movie uploads
});

// =====================================================
// REQUEST INTERCEPTOR
// Adds JWT token and configures request content type.
// =====================================================

API.interceptors.request.use(
  (config) => {
    const token = localStorage.getItem("accessToken");

    // Add authentication token when available.
    if (token) {
      config.headers.Authorization = `Bearer ${token}`;
    } else {
      delete config.headers.Authorization;
    }

    // FormData must use the multipart boundary generated by Axios.
    if (
      typeof FormData !== "undefined" &&
      config.data instanceof FormData
    ) {
      delete config.headers["Content-Type"];
      delete config.headers["content-type"];
    } else if (
      config.data &&
      typeof config.data === "object" &&
      !(config.data instanceof URLSearchParams) &&
      !(typeof FormData !== "undefined" &&
        config.data instanceof FormData)
    ) {
      config.headers["Content-Type"] = "application/json";
    }

    return config;
  },
  (error) => Promise.reject(error)
);

// =====================================================
// RESPONSE INTERCEPTOR
// Keeps API errors available to components.
// =====================================================

API.interceptors.response.use(
  (response) => response,
  (error) => {
    if (error.response) {
      console.error("API error:", {
        url: error.config?.url,
        status: error.response.status,
        data: error.response.data,
      });
    } else if (error.request) {
      console.error(
        "No response from Django server:",
        error.message
      );
    } else {
      console.error("Request setup error:", error.message);
    }

    return Promise.reject(error);
  }
);

export default API;
export { API };
